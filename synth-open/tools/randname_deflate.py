#!/usr/bin/env python3
"""Generate core/source/mtRandomNameTabs.{h,cpp}, the deflated random name tables, from core/source/names/word{1,2}.txt.

The word lists hold one word per line, in the order of the stock tables (the index a random number picks must keep its word). The tables
are the stock strings "_word_word_..._" (every word between two underscores), raw deflate (RFC 1951) compressed. mtRandomNameGenerator.cpp
inflates them once into SDRAM (core/libs/NewDisplay/inflate.cpp). The output is checked by inflating it again with zlib. The proof that
the names are unchanged is synth-open/tools/randname_test.sh (golden hash of 6,000 names made with the stock tables).

  randname_deflate.py <core/source>
"""
import os
import sys
import zlib


def best_deflate(raw):
    best = None
    for mem in range(1, 10):
        for strat in (zlib.Z_DEFAULT_STRATEGY, zlib.Z_FILTERED):
            co = zlib.compressobj(9, zlib.DEFLATED, -15, mem, strat)
            z = co.compress(raw) + co.flush()
            if best is None or len(z) < len(best):
                best = z
    assert zlib.decompress(best, -15) == raw
    return best


def main(src):
    words = {}
    for k in (1, 2):
        w = [l for l in open(os.path.join(src, "names", "word%d.txt" % k)).read().split("\n") if l]
        if len(w) != 1006 or any("_" in x or not x.isascii() for x in w):
            sys.exit("word%d.txt: %d words, 1006 expected, no underscores" % (k, len(w)))
        words[k] = ("_" + "_".join(w) + "_").encode()
    zs = {k: best_deflate(words[k]) for k in words}
    with open(os.path.join(src, "mtRandomNameTabs.h"), "w") as f:
        f.write("#pragma once\n// Generated by synth-open/tools/randname_deflate.py from names/word{1,2}.txt, do not edit.\n#include <stdint.h>\n\n")
        for k in (1, 2):
            f.write("constexpr uint32_t kRandomNameWord%dTabSize = %d;   // the table as text: _word_word_..._, with its end\n"
                    "extern const uint8_t randomNameWord%dTabDeflated[%d];\n" % (k, len(words[k]) + 1, k, len(zs[k])))
    with open(os.path.join(src, "mtRandomNameTabs.cpp"), "w") as f:
        f.write('// Generated by synth-open/tools/randname_deflate.py from names/word{1,2}.txt, do not edit.\n#include "mtRandomNameTabs.h"\n')
        for k in (1, 2):
            z = zs[k]
            rows = ",\n".join("    " + ", ".join("0x%02X" % b for b in z[i:i + 16]) for i in range(0, len(z), 16))
            f.write("\nconst uint8_t randomNameWord%dTabDeflated[%d] = {\n%s};\n" % (k, len(z), rows))
    print("word1 %d -> %d B, word2 %d -> %d B" % (len(words[1]) + 1, len(zs[1]), len(words[2]) + 1, len(zs[2])))


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
