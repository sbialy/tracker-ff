#!/usr/bin/env python3
"""Acceptance test of the synth engine plugins against the firmware's own validator.

    TOOLCHAIN=.../agt/10.3/bin/arm-none-eabi- /tmp/phzvenv/bin/python -I synth-open/tools/validate_synth.py DIR_OR_PLG...

Cuts checkSynth (and in, fn, kLayout, kSynthSectionMax) out of synth-open/plug_synth.cpp as it is, cross-compiles it for the
MK66 with the agt toolchain into a flat binary (chk.bin, kept next to the outputs with --keep DIR), loads every .plg the way the
firmware's attach does (emu_synth.load: rebased for its FlexNVM home, rw in SRAM, entry, init, query PLUG_EXT_SYNTH) and runs
the real checkSynth in Unicorn on that extension. An engine it rejects is listed in the picker but shows Missing when picked
(attach error 4), and no other test sees it: emu_synth.py and the module repositories' render checks never call checkSynth.

It also prints the facts the check is about (sections, formats), and fails when a plugin uses a format the firmware only has
for a built-in engine (PLUG_FMT_COUNT and up). Exit code 0 only when every synth plugin passes. Needs unicorn (pip).
"""
import os
import re
import struct
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
SO = os.path.dirname(HERE)
ROOT = os.path.dirname(SO)
sys.path.insert(0, os.path.join(SO, "plug"))   # python -I leaves the script directory out
import emu_synth as E  # noqa: E402
from unicorn import UC_ARCH_ARM, UC_MODE_THUMB, Uc  # noqa: E402
from unicorn.arm_const import (UC_ARM_REG_C1_C0_2, UC_ARM_REG_FPEXC, UC_ARM_REG_LR, UC_ARM_REG_R0, UC_ARM_REG_R1,  # noqa: E402
                               UC_ARM_REG_R2, UC_ARM_REG_R3, UC_ARM_REG_SP, UC_CPU_ARM_CORTEX_A15)

CHK_BASE = 0x1FFF8000          # the validator's text: SRAM, clear of emu_synth's harness and work areas
BASE, RWBASE = 0x10000000, 0x20027000   # an engine's FlexNVM home and its rw in the SRAM pool, as the firmware


def toolchain():
    if os.environ.get("TOOLCHAIN"):
        return os.environ["TOOLCHAIN"]
    c = os.path.join(ROOT, "agt", "10.3", "bin", "arm-none-eabi-")
    return c if os.path.exists(c + "gcc") else "arm-none-eabi-"


def extract():
    """The firmware's source of the check, unchanged: in(), fn(), checkSynth() and the constants it reads."""
    src = open(os.path.join(SO, "plug_synth.cpp")).read()
    lines = src.splitlines()
    want = []
    for pat, need in ((r"^constexpr uint32_t kLayout = ", True), (r"^constexpr uint32_t kSynthSectionMax = ", False)):
        m = [l for l in lines if re.match(pat, l)]   # kSynthSectionMax: absent before 1.2.0 (a literal 8 in the check)
        if len(m) != 1 and (need or m):
            sys.exit("validate_synth: %r not found once in plug_synth.cpp" % pat)
        want += m
    start = next(i for i, l in enumerate(lines) if l.startswith("inline bool in(const void* p"))
    chk = next(i for i, l in enumerate(lines) if l.startswith("bool checkSynth("))
    end = next(i for i in range(chk, len(lines)) if lines[i] == "}")
    return "\n".join(want + lines[start:end + 1])


def build(out):
    tc = toolchain()
    cpp = os.path.join(out, "chk.cpp")
    with open(cpp, "w") as f:
        f.write("""// generated by validate_synth.py from plug_synth.cpp
#include <stddef.h>
#include <stdint.h>
#include "plug/plug_abi.h"
#include "audio/synth_engine.h"
extern "C" size_t strnlen(const char* s, size_t n) { size_t i = 0; while (i < n && s[i]) i++; return i; }
extern "C" char* strchr(const char* s, int c) { for (;; s++) { if (*s == (char)c) return (char*)s; if (!*s) return 0; } }
namespace {
using namespace ot::audio;
%s
}
extern "C" uint32_t run_check(const plug_ext_synth* x, uintptr_t t, uint32_t tn, uintptr_t rw, uint32_t rwn)
{ return checkSynth(x, t, tn, rw, rwn); }
extern "C" uint32_t layout() { return kLayout; }
""" % extract())
    obj, elf, binf = (os.path.join(out, "chk." + e) for e in ("o", "elf", "bin"))
    flags = ["-mcpu=cortex-m4", "-mthumb", "-mfloat-abi=hard", "-mfpu=fpv4-sp-d16", "-Os", "-std=c++20", "-ffreestanding",
             "-fno-builtin", "-fno-exceptions", "-fno-rtti", "-ffunction-sections",
             "-I", SO, "-I", os.path.join(SO, "ot"), "-I", os.path.join(ROOT, "synth", "include")]
    for cmd in ([tc + "g++"] + flags + ["-c", cpp, "-o", obj],
                [tc + "ld", "-Ttext=0x%x" % CHK_BASE, "-e", "run_check", "--gc-sections", "-u", "layout", "-o", elf, obj],
                [tc + "objcopy", "-O", "binary", "-j", ".text", elf, binf]):
        r = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE)
        if r.returncode:
            sys.exit("validate_synth: FAILED " + " ".join(cmd) + "\n" + r.stderr.decode())
    syms = {}
    for line in subprocess.run([tc + "nm", elf], stdout=subprocess.PIPE, check=True).stdout.decode().splitlines():
        p = line.split()
        if len(p) == 3:
            syms[p[2]] = int(p[0], 16)
    data = open(binf, "rb").read()
    if any(s not in syms for s in ("run_check", "layout")):
        sys.exit("validate_synth: run_check or layout missing in chk.elf")
    # no data or bss: the check is pure code over the plugin's memory
    for line in subprocess.run([tc + "objdump", "-h", elf], stdout=subprocess.PIPE, check=True).stdout.decode().splitlines():
        p = line.split()
        if len(p) > 2 and p[1] in (".data", ".bss") and int(p[2], 16):
            sys.exit("validate_synth: chk.elf has %s" % p[1])
    return data, syms["run_check"], syms["layout"]


def fmt_count():
    m = re.search(r"PLUG_FMT_PCT = 0,(.*?)PLUG_FMT_COUNT", open(os.path.join(SO, "plug", "plug_abi.h")).read(), re.S)
    return len(re.findall(r"PLUG_FMT_\w+", m.group(1))) + 1


def one(path, chk, run_check, layout_fn, nfmt):
    uc = Uc(UC_ARCH_ARM, UC_MODE_THUMB)
    uc.ctl_set_cpu_model(UC_CPU_ARM_CORTEX_A15)
    uc.mem_map(E.SRAM, E.SRAM_SIZE)
    uc.mem_map(0x70000000, 0x100000)
    uc.mem_map(0x10000000, 0x40000)
    uc.reg_write(UC_ARM_REG_C1_C0_2, uc.reg_read(UC_ARM_REG_C1_C0_2) | (0xF << 20))
    uc.reg_write(UC_ARM_REG_FPEXC, 0x40000000)
    eng = E.load(uc, path, BASE, RWBASE)
    if eng["kind"] != 4:
        return None, "not a synth plugin (kind %d)" % eng["kind"]
    uc.mem_write(E.TRAP, b"\xfe\xe7")
    uc.mem_write(CHK_BASE, chk)
    stubs = E.TRAP + 0x100   # host table, ABI 1.1 (emu_synth.py): every service returns 0, init and query need none
    uc.mem_write(stubs, b"\x70\x47\x00\xbf" * 14)
    fields = [(15 + 2) * 4, 1, struct.unpack("<I", struct.pack("<f", 44117.64706))[0]] + [(stubs + 4 * i) | 1 for i in range(14)]
    uc.mem_write(E.WORK, struct.pack("<%dI" % len(fields), *fields))

    def call(fn, *args):
        uc.reg_write(UC_ARM_REG_SP, E.WORK + 0xE000)
        uc.reg_write(UC_ARM_REG_LR, E.TRAP | 1)
        for r, v in zip((UC_ARM_REG_R0, UC_ARM_REG_R1, UC_ARM_REG_R2, UC_ARM_REG_R3), args):
            uc.reg_write(r, v)
        uc.emu_start(fn | 1, E.TRAP, count=50_000_000)
        return uc.reg_read(UC_ARM_REG_R0)

    u32 = lambda p: struct.unpack("<I", bytes(uc.mem_read(p, 4)))[0]
    desc = call(eng["entry"], E.WORK, (1 << 16) | 1)
    if call(u32(desc + 28), E.WORK + 0x1000, E.WORK) != 0:
        return False, "init failed"
    ext = call(u32(desc + 44), 3)
    if not ext:
        return False, "no PLUG_EXT_SYNTH"
    # checkSynth(x, text, text bytes, rw, rw bytes): the firmware's arguments (plug_synth.cpp attach)
    uc.reg_write(UC_ARM_REG_SP, E.WORK + 0xE000 - 8)   # the fifth argument on the stack
    uc.mem_write(E.WORK + 0xE000 - 8, struct.pack("<II", eng["rw"], 0))
    uc.reg_write(UC_ARM_REG_LR, E.TRAP | 1)
    for r, v in zip((UC_ARM_REG_R0, UC_ARM_REG_R1, UC_ARM_REG_R2, UC_ARM_REG_R3), (ext, BASE, eng["text"], RWBASE)):
        uc.reg_write(r, v)
    uc.emu_start(run_check | 1, E.TRAP, count=50_000_000)
    ok = bool(uc.reg_read(UC_ARM_REG_R0) & 0xFF)
    fw_layout = call(layout_fn)
    x = struct.unpack("<IIiiiIIIIIIIiII", bytes(uc.mem_read(ext, 60)))
    name = bytes(uc.mem_read(x[5], 16)).split(b"\0")[0].decode(errors="replace")
    fmts = sorted({bytes(uc.mem_read(x[6] + 24 * i + 16, 1))[0] for i in range(min(x[7], 128))})
    why = []
    if x[1] != fw_layout:
        why.append("layout %08x, firmware %08x" % (x[1], fw_layout))
    if fmts and fmts[-1] >= nfmt:
        why.append("format %d is built-in only (PLUG_FMT_COUNT %d)" % (fmts[-1], nfmt))
        ok = False
    return ok, "%s params=%d sections=%d macros=%d voices=%d fmts=%s%s" % (
        name, x[7], x[9], x[11], x[13], fmts, ("  (" + ", ".join(why) + ")") if why else "")


def main():
    args = sys.argv[1:]
    keep = None
    if args[:1] == ["--keep"]:
        keep, args = args[1], args[2:]
    if not args:
        sys.exit(__doc__)
    plgs = []
    for a in args:
        plgs += sorted(os.path.join(a, f) for f in os.listdir(a) if f.endswith(".plg")) if os.path.isdir(a) else [a]
    with tempfile.TemporaryDirectory() as tmp:
        out = keep or tmp
        os.makedirs(out, exist_ok=True)
        chk, run_check, layout_fn = build(out)
        nfmt = fmt_count()
        print("checkSynth from synth-open/plug_synth.cpp: %d B at 0x%08x, PLUG_FMT_COUNT %d" % (len(chk), run_check, nfmt))
        n = bad = 0
        for p in plgs:
            try:
                ok, info = one(p, chk, run_check, layout_fn, nfmt)
            except Exception as e:   # noqa: BLE001 - a plugin that faults in the emulator is a failure, keep going
                ok, info = False, "ERROR %r" % e
            if ok is None:
                continue
            n += 1
            bad += not ok
            print("%-12s %s  %s" % (os.path.basename(p), "PASS  " if ok else "REJECT", info))
    print("validate_synth: %d of %d synth plugins PASS" % (n - bad, n))
    sys.exit(1 if bad or not n else 0)


if __name__ == "__main__":
    main()
