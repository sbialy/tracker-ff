#!/usr/bin/env python3
"""Generate core/source/playModeTabs.{h,cpp}, the deflated custom play orders (CS1..CS20), from core/source/names/playorder.txt.

playorder.txt holds one line per order with 128 STEP:FX entries (the stock table of playModeDefs.h). The table is the byte pairs
(stepNumberToPlay, fxOption) of strPlayOrderWithEffects, raw deflate (RFC 1951) compressed. core/source/playModeOrder.cpp inflates it once
into SDRAM at Sequencer::init. The output is checked by inflating it again with zlib. The proof that the table is unchanged is
synth-open/tools/playorder_test.sh (sha256 of the 5,120 bytes of the stock table).

  playorder_deflate.py <core/source>
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from deflate_best import best_deflate  # noqa: E402


def main(src):
    lines = [l for l in open(os.path.join(src, "names", "playorder.txt")).read().split("\n") if l and not l.startswith("#")]
    if len(lines) != 20:
        sys.exit("playorder.txt: %d orders, 20 expected" % len(lines))
    raw = bytearray()
    for l in lines:
        e = l.split()
        if len(e) != 128:
            sys.exit("playorder.txt: an order with %d entries, 128 expected" % len(e))
        for x in e:
            s, f = (int(v) for v in x.split(":"))
            if not (0 <= s <= 128 and 0 <= f <= 15):
                sys.exit("playorder.txt: bad entry " + x)
            raw += bytes([s, f])
    z = best_deflate(bytes(raw))
    with open(os.path.join(src, "playModeTabs.h"), "w") as f:
        f.write("#pragma once\n// Generated by synth-open/tools/playorder_deflate.py from names/playorder.txt, do not edit.\n#include <stdint.h>\n\n"
                "constexpr uint32_t kPlayOrderBytes = %d;   // the table as strPlayOrderWithEffects pairs (step, fx), 20 orders of 128\n"
                "extern const uint8_t playOrderDeflated[%d];\n" % (len(raw), len(z)))
    rows = ",\n".join("    " + ", ".join("0x%02X" % b for b in z[i:i + 16]) for i in range(0, len(z), 16))
    with open(os.path.join(src, "playModeTabs.cpp"), "w") as f:
        f.write('// Generated by synth-open/tools/playorder_deflate.py from names/playorder.txt, do not edit.\n#include "playModeTabs.h"\n\n'
                "const uint8_t playOrderDeflated[%d] = {\n%s};\n" % (len(z), rows))
    print("play orders %d -> %d B" % (len(raw), len(z)))


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
