"""The fx description popup texts of the release image as one raw deflate stream.

core/interface/core/interfaceFxDesc.h stays the source of the texts. This tool compiles synth-open/tools/fxdesc_dump.cpp against it
(FEATURE_SYNTH + FEATURE_SYNTH_OPEN, no FW_TRIM, the table of the release feature set), takes the FX_COUNT texts, each with its end 0, and
writes core/interface/core/interfaceFxDescZData.h with the deflated blob (synth-open/tools/deflate_best.py). interfaceFxDescZ.cpp inflates it
into SDRAM on the first use of the popup. Run it again after every edit of the table: fxdesc_test.sh fails on a stale blob.

  fxdesc_deflate.py [worktree root]
"""
import os
import subprocess
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from deflate_best import best_deflate  # noqa: E402


def dump(root, out):
    """Texts of the header table under the release feature set, the way fxnames_test.sh compiles interfaceDefs.h."""
    c = os.path.join(root, "core")
    here = os.path.join(root, "synth-open", "tools")
    exe = out + ".exe"
    cmd = ["c++", "-std=gnu++20", "-O0", "-include", "cstdint", "-w", "-Dstatic_assert(...)=", "-DFEATURE_SYNTH", "-DFEATURE_SYNTH_OPEN",
           "-I", c + "/include", "-I", c + "/config", "-I", c + "/source", "-I", c + "/libs/ElapsedMillis", "-I", c + "/libs",
           "-I", c + "/libs/NewDisplay", "-I", c + "/interface", "-I", c + "/interface/core", "-I", root + "/util/include",
           "-I", root + "/util/3rdparty", "-I", root + "/synth/include", os.path.join(here, "fxdesc_dump.cpp"), "-o", exe]
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode:
        sys.exit("compile failed:\n" + r.stderr[-3000:])
    r = subprocess.run([exe, out], capture_output=True, text=True)
    if r.returncode:
        sys.exit("dump failed:\n" + r.stderr[-1000:])
    os.unlink(exe)
    return int(r.stdout.split()[1]), open(out, "rb").read()


def main(root):
    with tempfile.TemporaryDirectory() as tmp:
        count, raw = dump(root, os.path.join(tmp, "desc.bin"))
    if raw.count(b"\0") != count or not raw.endswith(b"\0"):
        sys.exit("expected %d zero terminated texts" % count)
    z = best_deflate(raw)
    path = os.path.join(root, "core", "interface", "core", "interfaceFxDescZData.h")
    rows = ",\n".join("    " + ", ".join("0x%02X" % b for b in z[i:i + 16]) for i in range(0, len(z), 16))
    with open(path, "w") as f:
        f.write("// Generated by synth-open/tools/fxdesc_deflate.py from interfaceFxDesc.h, do not edit.\n"
                "// %d fx description texts, each with its end 0: %d B expanded, %d B deflated (raw RFC 1951).\n"
                "#pragma once\n#include <stdint.h>\n\n"
                "constexpr uint32_t kFxDescRawSize = %d;\nstatic const uint8_t kFxDescZ[%d] = {\n%s};\n" % (count, len(raw), len(z), len(raw), len(z), rows))
    print("fx descriptions: %d texts, %d B -> %d B" % (count, len(raw), len(z)))


if __name__ == "__main__":
    main(os.path.abspath(sys.argv[1]) if len(sys.argv) > 1 else os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..")))
