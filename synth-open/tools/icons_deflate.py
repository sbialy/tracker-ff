#!/usr/bin/env python3
"""Generate core/libs/images/icons_z.h, the deflated icon bitmaps of the FW_TRIM build (display.cpp bitmaps[]).

The L2/L4 icon arrays of core/libs/images/*.h are grouped by the #if that builds them in. Each group is one raw deflate stream
(RFC 1951) of the concatenated bitmaps, so the stream shares its Huffman tables (10,845 B of icons: 4,369 B one by one, 3,245 B joined).
display.cpp inflates a group into decompressedFontsCommonBuffer at boot and uploads every icon of it to the FT812 from there.

  icons_z.h   per group: iconsZ_<group>[] (deflate stream), its raw size, and per icon kZg_<array> (1 based group) and kZo_<array> (offset)

The originals stay in the *.h files (plain builds still use them, and this tool reads them). The bytes of a stream depend on the
zlib version: the committed header is what counts, the proof that it decodes to the originals is synth-open/tools/icons_inflate_test.sh.

  icons_deflate.py <core/libs/images>
"""
import os
import re
import sys
import zlib

# (group id, C++ name suffix, #if guard of display.cpp, arrays in the order of the stream)
GROUPS = [
    ("base", "", ["playIcon20x20", "loopIcon20x20", "doubleArrowL", "doubleArrowR", "arrowU", "arrowD", "battery_28x13_L4",
                  "battery_ch_28x19_L4"]),
    ("synth", "defined(FEATURE_SYNTH)",
     ["acd_mini_nomark_80x29_L2", "fat_mini_nomark_80x29_L2", "vap_mini_nomark_80x29_L2", "wtfm_mini_nomark_80x29_L2",
      "acd_med_108x40_L2", "fat_med_108x40_L2", "vap_med_108x40_L2", "wtfm_med_108x40_L2", "synth_env_18x14_L4",
      "synth_filter_18x13_L4", "synth_gear_18x18_L4", "synth_lfo_20x13_L4", "synth_macro_14x14_L4", "synth_mod_22x12_L4",
      "synth_osc_20x12_L4", "synth_FX_20x18_L4", "synth_cymbal_20x16_L4", "synth_hihat_20x16_L4", "synth_kick_16x19_L4",
      "synth_mixer_16x14_L4", "synth_percussion_16x16_L4", "synth_snare_20x16_L4", "synth_tom_20x16_L4"]),
    ("perc", "defined(FEATURE_SYNTH) && FW_ICON_PERC", ["perc_mini_nomark_80x29_L2", "perc_med_108x40_L2"]),
    ("phz", "defined(FEATURE_SYNTH) && (!defined(FEATURE_SYNTH_OPEN) || defined(SYNTH_ENGINE_PHZ))",
     ["phz_mini_nomark_80x29_L2", "phz_med_108x40_L2"]),
    ("dirt", "defined(FEATURE_SYNTH) && !defined(FEATURE_SYNTH_OPEN)",
     ["dirt_mini_nomark_80x28_L2", "dirt_med_108x40_L2", "synth_shaper_18x18_L4"]),
    ("chip", "defined(FEATURE_SYNTH) && FW_ICON_CHIP", ["chip_mini_nomark_80x28_L2", "chip_med_108x40_L2"]),
]

ARR = re.compile(r"const\s+uint8_t\s+(\w+)\s*\[\s*\d*\s*\]\s*=?\s*\{([^}]*)\}")


def read_arrays(img_dir):
    out = {}
    for fn in sorted(os.listdir(img_dir)):
        if not fn.endswith(".h"):
            continue
        t = open(os.path.join(img_dir, fn), encoding="utf8").read()
        t = re.sub(r"/\*.*?\*/", "", t, flags=re.S)
        t = re.sub(r"//[^\n]*", "", t)
        for m in ARR.finditer(t):
            out[m.group(1)] = bytes(int(x, 0) & 255 for x in re.findall(r"0[xX][0-9A-Fa-f]+|\d+", m.group(2)))
    return out


def main(img_dir):
    arrays = read_arrays(img_dir)
    lines = ["// Generated by synth-open/tools/icons_deflate.py from the icon arrays of this directory, do not edit.",
             "// One raw deflate stream per group of icons that a build gates together (display.cpp bitmaps[], FW_TRIM builds only).",
             "#ifndef LIBS_IMAGES_ICONS_Z_H_", "#define LIBS_IMAGES_ICONS_Z_H_", "",
             "#include <stdint.h>", "", "struct IconZGroup", "{", "    const uint8_t* stream;", "    uint16_t streamLen;",
             "    uint16_t rawLen;", "};", ""]
    table, zlens, rawtot = [], [], 0
    for gi, (gname, guard, names) in enumerate(GROUPS):
        raw = b""
        offs = []
        for n in names:
            if n not in arrays:
                sys.exit("array %s not found in %s" % (n, img_dir))
            offs.append((n, len(raw)))
            raw += arrays[n]
        co = zlib.compressobj(9, zlib.DEFLATED, -15)
        z = co.compress(raw) + co.flush()
        assert zlib.decompress(z, -15) == raw
        if len(raw) > 22396:
            sys.exit("group %s is %d B, the boot buffer holds 22,396" % (gname, len(raw)))
        rawtot += len(raw)
        zlens.append(len(z))
        lines.append("// group %d %s: %d icons, %d B raw, %d B deflated" % (gi + 1, gname, len(names), len(raw), len(z)))
        for n, o in offs:
            lines.append("constexpr uint8_t kZg_%s = %d;" % (n, gi + 1))
            lines.append("constexpr uint16_t kZo_%s = %d;" % (n, o))
        if guard:
            lines.append("#if " + guard)
        lines.append("static const uint8_t iconsZ_%s[%d] = {" % (gname, len(z)))
        for i in range(0, len(z), 16):
            lines.append("    " + ", ".join(str(b) for b in z[i:i + 16]) + ",")
        lines.append("};")
        if guard:
            lines.append("#endif")
        lines.append("")
        e = "{ iconsZ_%s, %d, %d }" % (gname, len(z), len(raw))
        table.append(("#if " + guard + "\n    " + e + ",\n#else\n    { nullptr, 0, 0 },\n#endif") if guard else "    " + e + ",")
    lines.append("// index = group id - 1, a group a build does not carry has no stream")
    lines.append("static const IconZGroup kIconZGroups[%d] = {" % len(GROUPS))
    lines += table
    lines.append("};")
    lines.append("")
    lines.append("#endif")
    open(os.path.join(img_dir, "icons_z.h"), "w", encoding="utf8").write("\n".join(lines) + "\n")
    print("icons_z.h: %d groups, %d B raw, deflated %s" % (len(GROUPS), rawtot, zlens))


if __name__ == "__main__":
    main(sys.argv[1])
