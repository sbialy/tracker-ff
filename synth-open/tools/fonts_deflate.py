#!/usr/bin/env python3
"""Generate the deflated font blobs of core/libs/fonts from the run length encoded originals in core/libs/fonts/rle.

Each rle/<font>_L4.cpp.rle is the stock array of {value, count} pairs (CompressedData, core/libs/NewDisplay/CompressionRLE.h).
This tool expands it to the L4 glyph bitmap the FT812 loads (what decompress() of the old array gave) and writes

  <font>_L4.cpp   const uint8_t <Name>_L4_deflated[N]   raw deflate stream (RFC 1951) of the expanded bitmap
  <font>_L4.h     the extern, <Name>_L4_rawSize (the expanded size) and the comment block of the original header

core/libs/NewDisplay/inflate.cpp decodes it into decompressedFontsCommonBuffer (display.cpp decompressFont). Every output is checked
by inflating it again with zlib. The bytes of a stream depend on the zlib version: the committed files are what counts, the proof that
they decode to the old bitmaps is synth-open/tools/font_inflate_test.sh (it expands the rle/ originals on its own).

  fonts_deflate.py <core/libs/fonts>
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from deflate_best import best_deflate  # noqa: E402

PAIR = re.compile(r"\{\s*(\d+)\s*,\s*(\d+)\s*\}")
SYM = re.compile(r"const\s+CompressedData\s+(\w+)_compressed\s*\[\s*(\d+)\s*\]")


def expand_rle(cpp_text):
    m = SYM.search(cpp_text)
    pairs = [(int(v), int(c)) for v, c in PAIR.findall(cpp_text)]
    if not m or len(pairs) != int(m.group(2)):
        raise SystemExit("array %s: %d pairs found, %s declared" % (m and m.group(1), len(pairs), m and m.group(2)))
    return m.group(1), b"".join(bytes([v]) * c for v, c in pairs)


def header_comments(h_text):
    # the leading /* ... */ blocks of the original header: converter command line, metrics
    out = []
    for m in re.finditer(r"/\*.*?\*/", h_text, re.S):
        if h_text[:m.start()].strip() and not h_text[:m.start()].rstrip().endswith("*/"):
            break
        out.append(m.group(0))
    return "\n".join(out)


def main(fonts):
    rle = os.path.join(fonts, "rle")
    total_raw = total_z = 0
    for fn in sorted(os.listdir(rle)):
        if not fn.endswith(".cpp.rle"):
            continue
        base = fn[:-len(".cpp.rle")]
        sym, raw = expand_rle(open(os.path.join(rle, fn), encoding="utf8").read())
        z = best_deflate(raw)
        new = sym + "_deflated"
        rows = ",\n".join("    " + ", ".join("0x%02X" % b for b in z[i:i + 16]) for i in range(0, len(z), 16))
        with open(os.path.join(fonts, base + ".cpp"), "w") as f:
            f.write('// Deflated (raw RFC 1951) glyph bitmap, %d B expanded. Generated by synth-open/tools/fonts_deflate.py from rle/%s, do not edit.\n'
                    '#include "%s.h"\n\nconst uint8_t %s[%d] = {\n%s};\n' % (len(raw), fn, base, new, len(z), rows))
        hdr = header_comments(open(os.path.join(rle, base + ".h.rle"), encoding="utf8").read())
        with open(os.path.join(fonts, base + ".h"), "w") as f:
            f.write('#pragma once\n// Generated by synth-open/tools/fonts_deflate.py, do not edit. Original (RLE) sources: rle/%s.{cpp,h}.rle\n%s\n'
                    '#include <stdint.h>\n\nconstexpr int %s_rawSize = %d;\nextern const uint8_t %s[%d];\n' % (base, hdr, sym + "_L4" if not sym.endswith("_L4") else sym, len(raw), new, len(z)))
        print("%-34s rle %6d B  expanded %6d B  deflated %5d B" % (base, sum(1 for _ in PAIR.finditer(open(os.path.join(rle, fn), encoding='utf8').read())) * 2, len(raw), len(z)))
        total_raw += len(raw)
        total_z += len(z)
    print("total expanded %d B, deflated %d B" % (total_raw, total_z))


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
