"""Boot logo as raw deflate: core/libs/images/rle/poly_logo_160x172_L8.cpp.rle (the stock {value, count} pairs) is expanded to the
160 x 172 L8 bitmap (27,520 B) and written as poly_logo_160x172_L8.{cpp,h} with a raw deflate stream (synth-open/tools/deflate_best.py).
display.cpp inflates it straight into poly_logo_160x172_l8 at boot (inflate.cpp, the same decoder as the fonts). The proof that the
bytes are the old ones is synth-open/tools/logo_inflate_test.sh.

  logo_deflate.py <core/libs/images>
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from deflate_best import best_deflate  # noqa: E402
from fonts_deflate import expand_rle, header_comments  # noqa: E402


def main(images):
    base = "poly_logo_160x172_L8"
    rle = os.path.join(images, "rle")
    sym, raw = expand_rle(open(os.path.join(rle, base + ".cpp.rle"), encoding="utf8").read())
    if len(raw) != 27520:
        sys.exit("logo expands to %d B, 27,520 expected" % len(raw))
    z = best_deflate(raw)
    new = sym + "_deflated"
    rows = ",\n".join("    " + ", ".join("0x%02X" % b for b in z[i:i + 16]) for i in range(0, len(z), 16))
    with open(os.path.join(images, base + ".cpp"), "w") as f:
        f.write('// Deflated (raw RFC 1951) 160x172 L8 logo bitmap, %d B expanded. Generated by synth-open/tools/logo_deflate.py from rle/%s.cpp.rle, do not edit.\n'
                '#include "%s.h"\n\nconst uint8_t %s[%d] = {\n%s};\n' % (len(raw), base, base, new, len(z), rows))
    hdr = header_comments(open(os.path.join(rle, base + ".h.rle"), encoding="utf8").read())
    with open(os.path.join(images, base + ".h"), "w") as f:
        f.write('#pragma once\n// Generated by synth-open/tools/logo_deflate.py, do not edit. Original (RLE) sources: rle/%s.{cpp,h}.rle\n%s\n'
                '#include <stdint.h>\n\nconstexpr int %s_rawSize = %d;\nextern const uint8_t %s[%d];\n' % (base, hdr, sym, len(raw), new, len(z)))
    print("%s: expanded %d B, deflated %d B" % (base, len(raw), len(z)))


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
